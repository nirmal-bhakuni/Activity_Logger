-- ============================================================
-- 01_schema.sql  -  Tables for the Activity Monitor project
-- ============================================================
-- WHAT THIS FILE DOES
--   Creates the database and all tables. Safe to run more than once
--   (it uses IF NOT EXISTS, so existing data is never deleted).
--
-- TABLE OVERVIEW
--   sessions            one row per monitoring run
--   process_snapshots   one row per visible app per check cycle
--                       includes idle and focused-window status
--   game_processes      process names counted as games
--   score_config        productivity score settings
--   ai_insights         saved AI-generated summaries and recommendations
--   employees           dashboard users, names, roles, and password hashes
--
-- FRESH DATABASE SETUP:
--   Run database/setup_all.sql.
--
-- EXISTING DATABASE UPGRADE:
--   Run the numbered files in database/migrations/ once.
--
-- SECURITY:
--   employees.password_hash stores hashes, never plaintext passwords.
--   Application names are currently allowed in Gemini input.
-- ============================================================

CREATE DATABASE IF NOT EXISTS activity_monitor;
USE activity_monitor;

-- One row per monitoring run of activity_monitor.exe
CREATE TABLE IF NOT EXISTS sessions (
    session_id         INT AUTO_INCREMENT PRIMARY KEY,
    start_time         DATETIME DEFAULT CURRENT_TIMESTAMP,
    end_time           DATETIME NULL,            -- NULL = session still running or was never closed
    total_idle_seconds INT DEFAULT 0,
    employee_id        VARCHAR(50),              -- from config.ini, e.g. EMP001
    machine_name       VARCHAR(100)              -- detected automatically from the PC name
);

-- One row per visible application per check cycle
CREATE TABLE IF NOT EXISTS process_snapshots (
    snapshot_id     INT AUTO_INCREMENT PRIMARY KEY,
    session_id      INT NOT NULL,
    process_name    VARCHAR(255),
    pid             INT,
    cpu_usage       FLOAT,                       -- percent
    memory_usage_mb FLOAT,
    is_idle         BOOLEAN,                     -- 1 if the user had been idle past the threshold
    is_focused      BOOLEAN NULL DEFAULT NULL,   -- NULL means the snapshot was recorded before focus tracking existed.
                                                -- 1 means the process had the foreground window.
                                                -- 0 means the process was visible but not focused.
    log_time        DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (session_id) REFERENCES sessions(session_id)
);

-- Process names that count as games when the productivity score is calculated
CREATE TABLE IF NOT EXISTS game_processes (
    process_name VARCHAR(255) PRIMARY KEY
);

-- Settings for the productivity score (one row, id = 1)
CREATE TABLE IF NOT EXISTS score_config (
    id                    INT PRIMARY KEY,
    game_weight           DOUBLE NOT NULL,       -- penalty per % of session spent gaming
    idle_weight           DOUBLE NOT NULL,       -- penalty per % of session spent idle
    min_session_sec       INT NOT NULL,          -- shorter sessions are not scored
    snapshot_interval_sec INT NOT NULL           -- must match SNAPSHOT_INTERVAL_SECONDS in activity_monitor.cpp
);

-- Table for storing AI-generated insights
-- Stores the exact sanitized JSON sent to Gemini and the validated response.
-- Employee and machine identity should not be included in input_json.
CREATE TABLE IF NOT EXISTS ai_insights (
    insight_id    INT AUTO_INCREMENT PRIMARY KEY,
    employee_id   VARCHAR(50) NOT NULL,
    generated_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
    model_name    VARCHAR(100),
    sessions_used INT,
    input_json    JSON,
    output_json   JSON,
    INDEX idx_insight_employee (employee_id, generated_at)
);

-- Dashboard login identities.
-- password_hash must be generated by the web application using a secure
-- password-hashing algorithm such as Werkzeug or bcrypt.
-- role controls access to employee or boss dashboard pages.
CREATE TABLE IF NOT EXISTS employees (
    employee_id   VARCHAR(50) PRIMARY KEY,
    employee_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          ENUM('employee', 'boss') NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_employees_role
ON employees(role);
